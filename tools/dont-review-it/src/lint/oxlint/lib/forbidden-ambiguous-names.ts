const isDigitsOnly = (word: string): boolean => /^\d+$/u.test(word);

const withoutTrailingDigits = (parts: readonly string[]): readonly string[] =>
  parts.length > 1 && isDigitsOnly(String(parts.at(-1)))
    ? withoutTrailingDigits(parts.slice(0, -1))
    : parts;

