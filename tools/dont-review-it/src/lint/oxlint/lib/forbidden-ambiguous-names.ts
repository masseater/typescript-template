const withoutLeadingQualifiers = (parts: readonly string[]): readonly string[] =>
  parts.length > 1 && MEANINGLESS_QUALIFIERS.has(String(parts.at(0)).toLowerCase())
    ? withoutLeadingQualifiers(parts.slice(1))
    : parts;

const normalizeIdentifierName = (spelled: string): string =>
  withoutLeadingQualifiers(withoutTrailingDigits(words(spelled))).join("");

export const createForbiddenNameMatcher = (
  patterns: readonly ForbiddenNamePattern[],
): ((name: string) => boolean) => {
  const matchers = patterns.map(({ pattern }) => new RegExp(pattern, "iu"));
  return (spelled) => {
    const normalizedText = normalizeIdentifierName(spelled);
    return normalizedText.length > 0 && matchers.some((matcher) => matcher.test(normalizedText));
  };
};
